//! The core game port of Your Only Move Is HUSTLE.
//!
//! This crate has no dependencies. See `README.md` for the reason: Charon
//! must extract the MIR of every function a Lean proof uses, so the port
//! does not link `fixed`, `fixed-sqrt`, or `fixed_trigonometry`. It copies
//! their algorithms instead.
//!
//! Modules: `fixed`, the fixed-point number type; `godot_hash`, Godot
//! 3.5.1's `hash()` builtin; `rng`, the logic RNG (Godot's PCG32 plus
//! `BetterRng`'s `choose` and `weighted_choice`); `physics`, the
//! native `FGObject` class's object physics (gravity, friction,
//! forces, movement, pushback); `tables`, the five official
//! characters' and their projectiles' data (generated by
//! `tools/tablegen`, see its README.md); `fixed_text`, `&str`/
//! `String` wrappers over `fixed`'s byte-based API, behind the `text`
//! feature (off by default). See
//! `docs/labbook/2026-11-13-core-game-scope-five-characters.md`,
//! decisions 4 and 5, and this crate's own README.md, "The core and the
//! shell".

pub mod fixed;
pub mod godot_hash;
pub mod physics;
pub mod rng;
pub mod tables;

#[cfg(feature = "text")]
pub mod fixed_text;
